#!/usr/bin/env python3
"""生成规则网格(raster) RTX LiDAR JSON 配置.

用途: 自定义 FOV 的固态 LiDAR 仿真配置. 基于一个现有 JSON 复制 profile 的
标量字段, 仅把 emitterStates 的 azimuthDeg/elevationDeg/fireTimeNs 重生成为
各向同性的规则网格 (非 ZVISION 真实非重复扫描图案).

生成后必须在 Isaac Sim 环境转换为 USD, 才能被 sensor_suite 加载:
    python tools/convert_lidar_json.py lidar_configs/json/<out>.json

用法示例 (120°×90°, 0.5° 分辨率 规则网格):
    python tools/gen_raster_lidar_json.py \
        --base lidar_configs/json/MLXS_nofire_quarter.json \
        --out  lidar_configs/json/raster_120x90.json \
        --az -60 60 --el -45 45 --step 0.5

用法示例 (120°×90°, 非重复散乱, 同真机 ML-Xs 风格):
    python tools/gen_raster_lidar_json.py \
        --base lidar_configs/json/MLXS_nofire_quarter.json \
        --out  lidar_configs/json/scatter_120x90.json \
        --az -60 60 --el -45 45 --mode scatter --n 27000

注意: 无论 grid/scatter, fireTimeNs 一律全 0. 摊开铺满整帧会让 Isaac RTX lidar
跨物理步攒欠账 -> 周期性丢帧 (顺1-2s -> 冻几秒), 与点数无关.
"""
import argparse
import json
import os


def linspace(a, b, n):
    if n <= 1:
        return [float(a)]
    return [a + (b - a) * i / (n - 1) for i in range(n)]


def count(span, step):
    return int(round(span / step)) + 1


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--base', required=True, help='模板 JSON (复制其 profile 标量字段)')
    ap.add_argument('--out', required=True, help='输出 JSON 路径')
    ap.add_argument('--az', nargs=2, type=float, default=[-60.0, 60.0],
                    metavar=('MIN', 'MAX'), help='方位角范围(度), 默认 -60 60 => 120° 水平')
    ap.add_argument('--el', nargs=2, type=float, default=[-45.0, 45.0],
                    metavar=('MIN', 'MAX'), help='俯仰角范围(度), 默认 -45 45 => 90° 垂直')
    ap.add_argument('--step', type=float, default=0.5,
                    help='角分辨率(度), az/el 各向同性, 默认 0.5 (仅 grid)')
    ap.add_argument('--mode', choices=['grid', 'scatter'], default='grid',
                    help='grid: 规则网格; scatter: 视场内非重复散乱 (似真机固态)')
    ap.add_argument('--n', type=int, default=27000,
                    help='scatter 模式发射点数, 默认 27000')
    ap.add_argument('--seed', type=int, default=None,
                    help='scatter 随机种子, 固定可复现; 默认随机')
    ap.add_argument('--name', default=None, help='覆盖顶层 name 字段')
    args = ap.parse_args()

    with open(args.base) as f:
        d = json.load(f)
    p = d['profile']

    if args.mode == 'scatter':
        import random
        rng = random.Random(args.seed)
        N = args.n
        az_arr = [rng.uniform(args.az[0], args.az[1]) for _ in range(N)]
        el_arr = [rng.uniform(args.el[0], args.el[1]) for _ in range(N)]
        n_el = n_az = None
    else:
        az_lin = linspace(args.az[0], args.az[1], count(args.az[1] - args.az[0], args.step))
        el_lin = linspace(args.el[0], args.el[1], count(args.el[1] - args.el[0], args.step))
        n_az, n_el = len(az_lin), len(el_lin)

        # 行优先 raster: 逐 elevation 行, 每行扫过全部 azimuth
        az_arr, el_arr = [], []
        for el in el_lin:
            for az in az_lin:
                az_arr.append(az)
                el_arr.append(el)
        N = len(az_arr)

    # 所有光线同一时刻发射 (fireTimeNs=0): 一次渲染到位. 摊开铺满整帧
    # (fire = i*frame_ns/N) 会让 Isaac RTX lidar 跨物理步攒欠账 -> 周期性丢帧
    # (顺1-2s -> 冻几秒), 与点数无关. 保持 0.
    fire = [0] * N

    p['numberOfEmitters'] = N
    p['numberOfChannels'] = N
    if args.mode == 'scatter':
        # 散乱无网格线/行概念, 保留 base 的 numLines 可按需, 不生成 numRaysPerLine
        p.pop('numRaysPerLine', None)
    else:
        p['numLines'] = n_el
        p['numRaysPerLine'] = [n_az] * n_el
    p['emitterStateCount'] = 1
    p['emitterStates'] = [{
        'azimuthDeg': [round(x, 4) for x in az_arr],
        'elevationDeg': [round(x, 4) for x in el_arr],
        'fireTimeNs': fire,
    }]

    if args.name:
        d['name'] = args.name
    kind = 'Scatter' if args.mode == 'scatter' else 'Raster grid'
    d['_comment1'] = (
        '%s generated by tools/gen_raster_lidar_json.py; '
        'FOV %.1f x %.1f deg (az[%.1f,%.1f] el[%.1f,%.1f]), '
        '%d emitters. NOT a real ZVISION scan pattern.' % (
            kind, args.az[1] - args.az[0], args.el[1] - args.el[0],
            args.az[0], args.az[1], args.el[0], args.el[1],
            N))

    out_abs = os.path.abspath(args.out)
    os.makedirs(os.path.dirname(out_abs), exist_ok=True)
    with open(out_abs, 'w') as f:
        json.dump(d, f)

    print('Wrote %s' % out_abs)
    print('  emitters=%d' % N)
    print('  azimuth   [%.2f, %.2f]  span=%.2f' % (min(az_arr), max(az_arr),
                                                   max(az_arr) - min(az_arr)))
    print('  elevation [%.2f, %.2f]  span=%.2f' % (min(el_arr), max(el_arr),
                                                   max(el_arr) - min(el_arr)))


if __name__ == '__main__':
    main()
